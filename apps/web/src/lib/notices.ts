/**
 * 공지사항 — 고객지원 게시판.
 *
 * 🔴 2026-09-09 CEO 지시 "고객지원에 공지사항 칸 하나 추가돼야 함."
 *    자료실(`lib/resources.ts`)과 같은 방식이다 — **틀만 만들고 내용은 비워 둔다.**
 *
 * ── 공지 추가하는 법 (CEO/담당자용) ─────────────────────────────
 *  1. 아래 NOTICES 배열 맨 앞에 한 줄 추가한다. id 는 겹치지 않는 영문·숫자면 된다.
 *  2. date 는 'YYYY-MM-DD'. 목록의 번호는 배열 길이에서 자동으로 매겨진다.
 *  3. body 를 적으면 제목을 눌렀을 때 본문이 펼쳐진다. 없으면 제목만 보이고 펼쳐지지 않는다.
 *
 * ⚠️ 여기 적는 순간 **누구나 읽는 공개 글**이 된다. 단가·원가·공급사명·고객 연락처를 적지 않는다.
 *    그리고 우리가 하지 않은 시공을 실적처럼 적지 않는다.
 */

export interface Notice {
  /** 목록 key. 겹치지 않게만 두면 된다 */
  id: string
  title: string
  /** YYYY-MM-DD */
  date: string
  /** 본문. 있으면 제목을 눌러 펼친다. 줄바꿈은 그대로 살아난다 */
  body?: string
}

/**
 * 🔴 비어 있는 것이 정상이다. 실제 공지가 생겼을 때 CEO 가 한 줄씩 추가한다.
 *    자리를 채우려고 없는 공지를 지어내지 마라.
 */
export const NOTICES: Notice[] = []
